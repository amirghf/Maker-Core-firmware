#pragma once
// کنترل PID هیتر اکسترودر (بند ۴.۴ و ۴.۹). هیچ هدر ST اینجا include نمی‌شود.
#include <stdint.h>
#include "temp_limits.h"

namespace mc {

// سقف دمای هدف ×۱۰ (2600 = 260 درجه). از حداکثر دما مشتق می‌شود (بند ۴.۶).
constexpr int32_t kHeaterExTargetCapX10 = kTempExMaxX10 - kTempExTargetBufferX10;   // 2600 = 260 درجه (از حداکثر دما مشتق می‌شود، بند ۴.۶)

enum class HeaterExState : uint8_t {
    Off       = 0,   // مسلح نیست یا هدف صفر است
    SensorBad = 1,   // سنسور سالم نیست (قطع، اتصال کوتاه، آماده نیست)
    FullOn    = 2,   // خیلی پایین‌تر از هدف: توان کامل
    Active    = 3,   // PID کار می‌کند
    CutOff    = 4,   // خیلی بالاتر از هدف: توان صفر
    Tuning    = 5    // تنظیم خودکار PID (M303) در جریان است (بند ۴.۹)
};

// وظیفه زمان‌بند (هر ۱۰۰ میلی‌ثانیه): توان هیتر اکسترودر را از PID می‌گذارد.
// فعلاً هدف و مسلح‌شدن از متغیرهای debug می‌آیند (در بند ۴.۸ تغییر می‌کند).
void mc_heater_ex_poll();

// آیا هیتر اکسترودر «درخواست‌شده» است؟ (مسلح و هدف بیشتر از صفر). برای حفاظت حداقل دما (بند ۴.۶).
bool mc_heater_ex_demanded();

// هدف اعمال‌شده ×۱۰ (بعد از سقف). ۰ یعنی مسلح نیست یا هدف صفر است. برای حفاظت‌های بند ۴.۷.
int32_t mc_heater_ex_target_x10();

// آیا هیتر اکسترودر در «حالت تست» است؟ (mc_dbg_03_hex_arm برابر ۱). در این حالت M104 و M109 خطا می‌دهند.
bool mc_heater_ex_test_mode();

// هدف G-code را می‌گذارد (×۱۰). منفی ← ۰، بالاتر از سقف ← سقف. مقدار واقعاً ذخیره‌شده را برمی‌گرداند.
int32_t mc_heater_ex_set_target_x10(int32_t t_x10);

// ضرایب PID را می‌گذارد (×۱۰۰؛ مثلاً 2000 = 20.00). برای M303 با U1 (بند ۴.۹). تا ریست می‌ماند؛ ذخیره دائمی کار بند ۷.۳ است.
void mc_heater_ex_set_gains_x100(uint32_t kp_x100, uint32_t ki_x100, uint32_t kd_x100);

}  // namespace mc
