#pragma once
// خط‌خوان: بایت‌های دریافتی از کامپیوتر را به خط کامل تبدیل می‌کند.
// فقط از hal_serial استفاده می‌کند. هیچ هدر ST اینجا include نمی‌شود.
#include <stdint.h>

namespace mc {

constexpr uint16_t kLineMaxChars = 96;   // حداکثر طول یک خط (بدون پایان‌دهنده)

// هر دور حلقه اصلی (یا با دوره کوتاه) صدا زده شود. بایت‌ها را می‌خواند و خط کامل می‌سازد.
// پایان خط: CR یا LF یا هر دو. خط خالی نادیده گرفته می‌شود.
// بایت‌های کنترلی (کمتر از ۰x۲۰ و ۰x۷F) نادیده گرفته می‌شوند.
// تا وقتی یک خط کامل برداشته نشده (mc_line_release)، بایت جدیدی خوانده نمی‌شود.
// خط بلندتر از kLineMaxChars کنار گذاشته می‌شود و یک خطا لاگ می‌شود.
void mc_line_poll();

// آیا یک خط کامل آماده برداشتن است؟
bool mc_line_ready();
// متن خط آماده (با صفر تمام می‌شود). فقط وقتی mc_line_ready() درست است معتبر است.
const char* mc_line_text();
// طول خط آماده (تعداد نویسه‌ها).
uint16_t mc_line_length();
// خط آماده را برمی‌دارد تا خط بعدی خوانده شود.
void mc_line_release();

}  // namespace mc
